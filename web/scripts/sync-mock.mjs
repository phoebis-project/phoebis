#!/usr/bin/env node
// Writes the admin fixtures into the mock as one module, so every mock row can start from a real answer and
// the sync test can tell a stale copy from a fresh one byte for byte. Run after `PHOEBIS_WRITE_FIXTURES=1 cargo
// test -p phoebis-admin --test fixtures` re-captures a route.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fixturesDir = join(here, '..', 'test', 'fixtures');
const outDir = join(here, '..', 'src', 'mock', 'generated');

/** The module's text, deterministic for a given fixture set: names sorted, two-space JSON, one trailing newline. */
export function render(dir = fixturesDir) {
  const names = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
  const entries = Object.fromEntries(names.map((name) => {
    const { route, body } = JSON.parse(readFileSync(join(dir, `${name}.json`), 'utf8'));
    return [name, { route, body }];
  }));
  return [
    '// Generated by scripts/sync-mock.mjs from web/test/fixtures; run `npm run sync-mock` after a capture.',
    '// Do not edit: the sync test compares this file with a fresh render.',
    '',
    'export interface Fixture {',
    '  route: string;',
    '  body: unknown;',
    '}',
    '',
    `export const FIXTURES: Record<string, Fixture> = ${JSON.stringify(entries, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'fixtures.ts'), render());
  console.log(`wrote ${join(outDir, 'fixtures.ts')}`);
}
